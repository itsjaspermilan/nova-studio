/// Appends one sprite per lit pixel. `solid_uv` must sample opaque white.
pub fn draw_text(
    out: &mut Vec<SpriteInstance>,
    solid_uv: [f32; 4],
    x: f32,
    y: f32,
    pixel: f32,
    color: [u8; 4],
    text: &str,
) {
    let mut cursor = x;
    let mut line = y;
    for c in text.chars() {
        if c == '\n' {
            cursor = x;
            line += pixel * 9.0;
            continue;
        }
        for (row, bits) in rows(c).iter().enumerate() {
            for (col, bit) in bits.bytes().enumerate() {
                if bit == b'1' {
                    out.push(SpriteInstance {
                        center: [
                            cursor + (col as f32 + 0.5) * pixel,
                            line + (row as f32 + 0.5) * pixel,
                        ],
                        size: [pixel, pixel],
                        uv: solid_uv,
                        color,
                        rotation: 0.0,
                    });
                }
            }
        }
        cursor += pixel * 6.0;
    }
}

pub fn text_width(pixel: f32, text: &str) -> f32 {
    text.lines().map(|l| l.chars().count()).max().unwrap_or(0) as f32 * pixel * 6.0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_wide() {
        for c in ('0'..='9').chain('A'..='Z').chain(".,:-_/%()=? ".chars()) {
            assert!(rows(c).iter().all(|r| r.len() == 5), "glyph {c}");
        }
    }

    #[test]
    fn draw_text_counts_lit_pixels() {
        let mut out = Vec::new();
        draw_text(&mut out, [0.0; 4], 0.0, 0.0, 1.0, [255; 4], "I");
        let lit: usize = rows('I')
            .iter()
            .map(|r| r.bytes().filter(|&b| b == b'1').count())
            .sum();
        assert_eq!(out.len(), lit);
    }
}
