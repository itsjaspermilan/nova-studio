/// What is drawn for a character the font does not have.
const UNKNOWN = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f];

export const GLYPH_W = 5;
export const GLYPH_H = 7;

/// How many pixels wide and tall a text is at a scale (a new line starts a new row; letters are one pixel apart, rows two).
export function textSize(text: string, scale = 1): { w: number; h: number } {
  const lines = text.split("\n");
  const longest = Math.max(...lines.map((l) => l.length));
  return { w: Math.max(0, longest * (GLYPH_W + 1) - 1) * scale, h: lines.length * (GLYPH_H + 2) * scale - 2 * scale };
}

/// Draws the text with its top left corner at (x, y); pixels outside the raster are dropped. Returns the box it covers.
export function drawText(r: Raster, x: number, y: number, text: string, color: Rgba, scale = 1): { w: number; h: number } {
  const s = Math.max(1, Math.round(scale));
  text.split("\n").forEach((line, row) => {
    [...line].forEach((ch, col) => {
      const glyph = G[ch.toUpperCase()] ?? UNKNOWN;
      for (let gy = 0; gy < GLYPH_H; gy++) {
        for (let gx = 0; gx < GLYPH_W; gx++) {
          if (!(glyph[gy]! & (1 << (GLYPH_W - 1 - gx)))) continue;
          for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) setPixel(r, x + (col * (GLYPH_W + 1) + gx) * s + dx, y + (row * (GLYPH_H + 2) + gy) * s + dy, color);
        }
      }
    });
  });
  return textSize(text, s);
}

/// Whether the font has a glyph for the character (lower case counts as its capital).
export const hasGlyph = (ch: string) => ch.toUpperCase() in G;
